import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, writeFileSync, readFileSync, rmSync, existsSync, copyFileSync } from 'node:fs';
import path from 'node:path';
import { CACHE } from '../lib/config.mjs';
import { backupText } from '../scripts/backup-text.mjs';

test('text backup preserves old versions and deleted files, excludes credentials, detects damage and restores UTF-8', t => {
  mkdirSync(CACHE, { recursive: true });
  const fixture = mkdtempSync(path.join(CACHE, 'text-backup-test-'));
  t.after(() => rmSync(fixture, { recursive: true, force: true }));
  const root = path.join(fixture, 'project'), destination = path.join(fixture, 'backup');
  const put = (file, content) => {
    const target = path.join(root, file);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content);
  };
  put('Harmonia/config/PERSONA.md', '达妮娅的原始人设');
  put('Harmonia/memory/memories.json', '{"facts":["记忆"]}');
  put('Harmonia/memory/group_slang.json', '{}');
  put('Harmonia/memory/兴趣.md', '主人兴趣');
  put('Harmonia/runtime/sessions/owner-private.json', '[{"text":"最近对话"}]');
  put('旧bot人设文档/达妮娅/旧版.md', '旧人设');
  put('Harmonia/docs/说明.md', '说明');
  for (const file of ['Harmonia/config/.env', 'Harmonia/config/onebot.json', 'Harmonia/runtime/wechat-auth.json', '.cache/secret.txt', 'Harmonia/vendor/secret.md']) put(file, 'SECRET');
  const options = { root, destination };
  const first = backupText(options);
  assert.equal(first.changed, true);
  assert.equal(first.files, 7);
  const manifest = JSON.parse(readFileSync(path.join(first.snapshot, 'manifest.json'), 'utf8'));
  assert.equal(Object.keys(manifest.sha256).length, 7);
  assert.equal(existsSync(path.join(first.snapshot, 'Harmonia/config/.env')), false);
  assert.equal(backupText(options).changed, false);
  rmSync(path.join(root, '.cache'), { recursive: true, force: true });
  assert.equal(backupText(options).changed, false, 'Clearing project cache must not break or duplicate completed backups');
  put('Harmonia/config/PERSONA.md', '新的人设');
  const second = backupText(options);
  assert.notEqual(second.snapshot, first.snapshot);
  assert.equal(readFileSync(path.join(first.snapshot, 'Harmonia/config/PERSONA.md'), 'utf8'), '达妮娅的原始人设');
  rmSync(path.join(root, 'Harmonia/memory/兴趣.md'));
  const third = backupText(options);
  assert.equal(third.files, 6);
  assert.equal(existsSync(path.join(first.snapshot, 'Harmonia/memory/兴趣.md')), true);
  writeFileSync(path.join(third.snapshot, 'Harmonia/config/PERSONA.md'), 'damaged');
  const repaired = backupText(options);
  assert.equal(repaired.changed, true, 'Corrupt backups must not be treated as an unchanged success');
  writeFileSync(path.join(repaired.snapshot, 'manifest.json'), '{partial');
  assert.equal(backupText(options).changed, true, 'An interrupted manifest must not block future backups');
  put('Harmonia/memory/memories.json', '{invalid');
  assert.throws(() => backupText(options), SyntaxError);
  put('Harmonia/memory/memories.json', '{}');
  rmSync(path.join(root, 'Harmonia/config/PERSONA.md'));
  assert.throws(() => backupText(options), /Required source is missing/);
  const restored = path.join(fixture, '恢复人设.md');
  copyFileSync(path.join(first.snapshot, 'Harmonia/config/PERSONA.md'), restored);
  assert.equal(readFileSync(restored, 'utf8'), '达妮娅的原始人设');
  assert.throws(() => backupText({ root, destination: path.join(root, 'backup') }), /outside the source/);
});
